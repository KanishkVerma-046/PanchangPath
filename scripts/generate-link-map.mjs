#!/usr/bin/env node
// Scans src/pages/**/*.astro for <Layout title="..." description="..."> props
// and writes a Markdown internal-link table for the seo-content-writer skill.
// Re-run this after adding or removing pages: node scripts/generate-link-map.mjs

import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, relative, dirname, sep } from 'node:path';

const ROOT = process.cwd();
const PAGES_DIR = join(ROOT, 'src', 'pages');
const OUTPUT_FILE = join(ROOT, '.claude', 'skills', 'seo-content-writer', 'references', 'internal-links.md');

function walk(dir) {
  let files = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      files = files.concat(walk(full));
    } else if (entry.isFile() && entry.name.endsWith('.astro')) {
      files.push(full);
    }
  }
  return files;
}

function fileToUrl(filePath) {
  let rel = relative(PAGES_DIR, filePath).split(sep).join('/');
  rel = rel.replace(/\.astro$/, '');
  if (rel === 'index') return '/';
  if (rel.endsWith('/index')) rel = rel.slice(0, -'/index'.length);
  return '/' + rel;
}

function decodeAndEscape(str) {
  return str
    .replace(/&amp;/g, '&')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/\|/g, '\\|');
}

const links = [];
for (const file of walk(PAGES_DIR)) {
  const rel = relative(PAGES_DIR, file).split(sep).join('/');
  if (rel.includes('[')) continue; // dynamic routes have no single canonical URL to link to
  if (rel === '404.astro') continue; // not a real content link target

  const src = readFileSync(file, 'utf-8');
  const layoutMatch = src.match(/<Layout\b([\s\S]*?)>/);
  if (!layoutMatch) continue;
  const propsBlock = layoutMatch[1];

  const titleMatch = propsBlock.match(/\btitle="([^"]*)"/);
  if (!titleMatch) continue; // title is a JS expression, not a static string — skip

  const descMatch = propsBlock.match(/\bdescription="([^"]*)"/);

  links.push({
    url: fileToUrl(file),
    title: decodeAndEscape(titleMatch[1]),
    description: descMatch ? decodeAndEscape(descMatch[1]) : '',
  });
}

links.sort((a, b) => a.url.localeCompare(b.url));

const header = [
  '# Internal Link Map',
  '',
  'Auto-generated by `scripts/generate-link-map.mjs` — do not hand-edit.',
  'Re-run the script after adding or removing pages: `node scripts/generate-link-map.mjs`',
  '',
  '| URL | Title | Description |',
  '|---|---|---|',
].join('\n');

const rows = links.map(l => `| ${l.url} | ${l.title} | ${l.description} |`).join('\n');

mkdirSync(dirname(OUTPUT_FILE), { recursive: true });
writeFileSync(OUTPUT_FILE, header + '\n' + rows + '\n');

console.log(`Wrote ${links.length} internal links to ${relative(ROOT, OUTPUT_FILE)}`);
